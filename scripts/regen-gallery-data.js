const fs = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

const PROJECT_ROOT = path.resolve(__dirname, "..");
const GALLERY_DIR = path.join(PROJECT_ROOT, "public", "assets", "gallery");
const DATA_OUT = path.join(PROJECT_ROOT, "app", "data", "gallery-images.ts");
const JSON_OUT = path.join(GALLERY_DIR, "manifest.json");

const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const VIDEO_EXTS = new Set([".mp4", ".mov", ".webm"]);

// Argi files start with 20251219_, Max files start with 20251212_ or are IMG_1989/IMG_1990 etc.
function classify(filename) {
  if (filename.startsWith("20251219_")) {
    return { event: "argi", eventName: "Argi's Party", eventType: "Private Party" };
  }
  return { event: "max", eventName: "SYNC Xmas Party", eventType: "Corporate Event" };
}

async function main() {
  const entries = (await fs.promises.readdir(GALLERY_DIR)).sort();
  const records = [];

  for (const name of entries) {
    const fullPath = path.join(GALLERY_DIR, name);
    const stat = await fs.promises.stat(fullPath);
    if (!stat.isFile()) continue;
    if (name === "manifest.json") continue;

    const ext = path.extname(name).toLowerCase();
    const meta = classify(name);

    if (IMAGE_EXTS.has(ext)) {
      const m = await sharp(fullPath, { failOn: "none" }).metadata();
      records.push({
        src: `/assets/gallery/${name}`,
        alt: `${meta.eventName} photo booth strip`,
        event: meta.event,
        eventName: meta.eventName,
        eventType: meta.eventType,
        type: "image",
        width: m.width || 0,
        height: m.height || 0,
      });
    } else if (VIDEO_EXTS.has(ext)) {
      records.push({
        src: `/assets/gallery/${name}`,
        alt: `${meta.eventName} photo booth video`,
        event: meta.event,
        eventName: meta.eventName,
        eventType: meta.eventType,
        type: "video",
        width: 0,
        height: 0,
      });
    }
  }

  const ts = `// AUTO-GENERATED by scripts/regen-gallery-data.js — do not edit by hand.
// Run \`node scripts/regen-gallery-data.js\` to regenerate.

export interface GalleryImage {
  src: string;
  alt: string;
  event: 'argi' | 'max';
  eventName: string;
  eventType: string;
  type: 'image' | 'video';
  width: number;
  height: number;
}

export const galleryImages: GalleryImage[] = ${JSON.stringify(records, null, 2)};
`;

  await fs.promises.writeFile(DATA_OUT, ts, "utf8");
  await fs.promises.writeFile(JSON_OUT, JSON.stringify(records, null, 2), "utf8");

  const argi = records.filter((r) => r.event === "argi").length;
  const max = records.filter((r) => r.event === "max").length;
  console.log(`Wrote ${records.length} entries (argi=${argi}, max=${max})`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
